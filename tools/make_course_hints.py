"""Write team_planner/config/course_hints.json: COURSE-SPECIFIC waypoints from the launch mark to the
pad, planned on the course model. Run with the rover env:  python tools/make_course_hints.py [--window]

Waypoints are in the COURSE frame (metres, OBJ axes: +y is the north net side). The file also records the
start pose the drone is assumed to have: on the launch mark, nose toward +y (up the first corridor).
Place the drone that way, or edit "start". Layout-specific by design: flying it in a scored run costs
generality points and the code review will flag it.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "planner"))
from course_fixture import plan_course_route   # noqa: E402

OBJ = os.path.join(ROOT, "dronehacks-course-v3.obj")
OUT = os.path.join(ROOT, "team_planner", "config", "course_hints.json")

if __name__ == "__main__":
    via_window = "--window" in sys.argv
    launch, pad, wps = plan_course_route(OBJ, avoid_window=not via_window)
    hints = {
        "_note": "COURSE-SPECIFIC. Generated by tools/make_course_hints.py from dronehacks-course-v3.obj "
                 "(preliminary layout). Course frame, metres.",
        "route_via": "window" if via_window else "gate_b",
        "start": {"x": launch[0], "y": launch[1], "heading_deg": 90.0},
        "waypoints": [{"name": f"wp{i + 1}", "x": x, "y": y} for i, (x, y) in enumerate(wps)],
        "pad": {"x": round(pad[0], 3), "y": round(pad[1], 3)},
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(hints, fh, indent=2)
    print(f"wrote {OUT}: {len(wps)} waypoints via {hints['route_via']}")
