"""Copy the planner's flight-side modules into the ROS package, with package-relative imports.

planner/ is the single source of truth (it is also what the simulator tests). Run this after
changing theta_star.py, mapping.py or navigator.py:   python tools/sync_planner_core.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "planner")
DST = os.path.join(ROOT, "team_planner", "team_planner", "planner_core")
MODULES = ("theta_star", "mapping", "navigator")

os.makedirs(DST, exist_ok=True)
with open(os.path.join(DST, "__init__.py"), "w", encoding="utf-8") as fh:
    fh.write('"""GENERATED by tools/sync_planner_core.py from planner/. Do not edit here."""\n')
for name in MODULES:
    with open(os.path.join(SRC, name + ".py"), encoding="utf-8") as fh:
        text = fh.read()
    for other in MODULES:
        text = re.sub(rf"^from {other} import", f"from .{other} import", text, flags=re.M)
    header = f"# GENERATED by tools/sync_planner_core.py from planner/{name}.py. Do not edit here.\n"
    with open(os.path.join(DST, name + ".py"), "w", encoding="utf-8") as fh:
        fh.write(header + text)
    print("synced", name)
